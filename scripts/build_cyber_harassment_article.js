function cell(segs, width, o = {}) {
  const keep = !!o.keepNext;
  return new TableCell({
    borders,
    width: { size: width, type: WidthType.DXA },
    shading: o.fill ? { fill: o.fill, type: ShadingType.CLEAR, color: "auto" } : undefined,
    verticalAlign: VerticalAlign.CENTER,
    margins: { top: 60, bottom: 60, left: 100, right: 100 },
    children: [
      new Paragraph({
        bidirectional: true,
        alignment: o.center ? AlignmentType.CENTER : AlignmentType.BOTH,
        keepNext: keep,
        spacing: { before: 0, after: 0, line: 300 },
        children: toRuns(segs, { size: hp(BODY_PT - 2), bold: !!o.bold }),
      }),
    ],
  });
}

function table(widths, header, rows) {
  return new Table({
    visuallyRightToLeft: true,
    width: { size: widths.reduce((a, b) => a + b, 0), type: WidthType.DXA },
    columnWidths: widths,
    rows: [
      new TableRow({
        tableHeader: true,
        cantSplit: true,
        children: header.map((h, i) => cell(h, widths[i], { fill: "D9E2F3", bold: true, center: true, keepNext: true })),
      }),
      ...rows.map(
        (r, ri) =>
          new TableRow({
            cantSplit: true,
            children: r.map((c, i) =>
              cell(c, widths[i], { fill: ri % 2 ? "F7F9FC" : undefined, keepNext: ri < rows.length - 1 })
            ),
          })
      ),
    ],
  });
}

