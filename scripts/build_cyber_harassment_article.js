function bullet(segs, ref = "bullets") {
  return new Paragraph({
    bidirectional: true,
    alignment: AlignmentType.BOTH,
    numbering: { reference: ref, level: 0 },
    spacing: { before: 0, after: 80, line: 340 },
    children: toRuns(segs),
  });
}

function numbered(segs, ref) {
  return bullet(segs, ref);
}

// legal-text quotation (indented box-ish paragraph)
function quote(text) {
  return new Paragraph({
    bidirectional: true,
    alignment: AlignmentType.BOTH,
    spacing: { before: 80, after: 160, line: 340 },
    indent: { left: 567, right: 567 },
    border: {
      right: { style: BorderStyle.SINGLE, size: 12, color: "7F8C8D", space: 8 },
    },
    shading: { type: ShadingType.CLEAR, fill: "F3F4F6", color: "auto" },
    children: mixed(text, { size: hp(BODY_PT - 1) }),
  });
}

function enPara(text, o = {}) {
  return new Paragraph({
    bidirectional: false,
    alignment: AlignmentType.LEFT,
    spacing: { before: 0, after: 100, line: 300 },
    indent: o.hanging ? { left: 567, hanging: 567 } : undefined,
    children: [new TextRun({ text, font: { ascii: EN_FONT, hAnsi: EN_FONT, cs: EN_FONT }, size: o.size || hp(11), italics: !!o.italics })],
  });
}

// APA-style reference entry (Persian, RTL, hanging indent)
function faRef(segs) {
  return new Paragraph({
    bidirectional: true,
    alignment: AlignmentType.BOTH,
    spacing: { before: 0, after: 100, line: 320 },
    indent: { left: 567, hanging: 567 },
    children: toRuns(segs, { size: hp(BODY_PT - 1) }),
  });
}

// English reference entry with an italic part: [before, italic, after]
function enRef(before, ital, after) {
  const f = { ascii: EN_FONT, hAnsi: EN_FONT, cs: EN_FONT };
  return new Paragraph({
    bidirectional: false,
    alignment: AlignmentType.LEFT,
    spacing: { before: 0, after: 100, line: 300 },
    indent: { left: 567, hanging: 567 },
    children: [
      new TextRun({ text: before, font: f, size: hp(11) }),
      new TextRun({ text: ital, font: f, size: hp(11), italics: true }),
      new TextRun({ text: after, font: f, size: hp(11) }),
    ],
  });
}

