// ---------- text helpers (mixed RTL/LTR) ----------
const LATIN = /[A-Za-z0-9(][\x20-\x7E§–’]*[A-Za-z0-9)]|[A-Za-z]/g;

function faRun(text, o = {}) {
  // "۲-۳" would be reordered as one LTR number; an en dash keeps RTL reading order.
  text = text.replace(/([\u06F0-\u06F9])-(?=[\u06F0-\u06F9])/g, "$1\u2013");
  return new TextRun({
    text,
    rightToLeft: true,
    font: { ascii: FA_FONT, hAnsi: FA_FONT, cs: FA_FONT, eastAsia: FA_FONT },
    size: o.size || BODY,
    sizeComplexScript: o.size || BODY,
    bold: !!o.bold,
    boldComplexScript: !!o.bold,
    italics: false,
    color: o.color,
    language: { bidirectional: "fa-IR" },
  });
}

function enRun(text, o = {}) {
  // keep parenthetical Latin citations on one line
  if (text.startsWith("(")) text = text.replace(/ /g, "\u00A0");
  return new TextRun({
    text,
    rightToLeft: false,
    font: { ascii: EN_FONT, hAnsi: EN_FONT, cs: EN_FONT },
    size: o.enSize || (o.size ? o.size - 2 : EN_BODY),
    bold: !!o.bold,
    color: o.color,
  });
}

function mixed(text, o = {}) {
  const out = [];
  let last = 0;
  LATIN.lastIndex = 0;
  let m;
  while ((m = LATIN.exec(text))) {
    if (m.index > last) out.push(faRun(text.slice(last, m.index), o));
    out.push(enRun(m[0], o));
    last = m.index + m[0].length;
  }
  if (last < text.length) out.push(faRun(text.slice(last), o));
  return out;
}

// segments: string | {b: string} | {fn: number}
function toRuns(segs, o = {}) {
  if (!Array.isArray(segs)) segs = [segs];
  const runs = [];
  for (const s of segs) {
    if (typeof s === "string") runs.push(...mixed(s, o));
    else if (s.b) runs.push(...mixed(s.b, { ...o, bold: true }));
    else if (s.fn) runs.push(new FootnoteReferenceRun(s.fn));
  }
  return runs;
}

function P(segs, o = {}) {
  return new Paragraph({
    bidirectional: true,
    alignment: o.align || AlignmentType.BOTH,
    spacing: { before: o.before ?? 0, after: o.after ?? 120, line: o.line ?? 360 },
    indent: o.noIndent ? undefined : { firstLine: o.firstLine ?? 0 },
    keepNext: !!o.keepNext,
    children: toRuns(segs, o),
  });
}

